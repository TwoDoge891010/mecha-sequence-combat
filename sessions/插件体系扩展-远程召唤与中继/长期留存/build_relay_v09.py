def sheet_header(ws, title, width_map):
    ws.cell(1, 1, title).font = TITLE_FONT
    ws.cell(1, 1).fill = TITLE_FILL
    for col, w in width_map.items():
        ws.column_dimensions[col].width = w

def write_table(ws, start_row, headers, rows):
    ws.cell(start_row, 1, "")
    for j, h in enumerate(headers, 1):
        c = ws.cell(start_row, j, h)
        c.font = HDR_FONT; c.fill = HDR_FILL; c.border = BORDER
        c.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
    for i, row in enumerate(rows):
        r = start_row + 1 + i
        for j, v in enumerate(row, 1):
            c = ws.cell(r, j, v)
            c.font = BODY_FONT; c.border = BORDER; c.alignment = WRAP_TOP
            if i % 2 == 1:
                c.fill = ZEBRA

def note(ws, r, text):
    c = ws.cell(r, 1, text); c.font = NOTE_FONT; c.alignment = WRAP_TOP
    return r + 1


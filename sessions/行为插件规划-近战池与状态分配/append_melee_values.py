def append_rows(ws, rows, ncols):
    start = ws.max_row + 1
    for i, vals in enumerate(rows):
        r = start + i
        tmpl = 19 if r % 2 else 20
        for c in range(1, ncols + 1):
            ws.cell(r, c)._style = copy(ws.cell(tmpl, c)._style)
        for c, v in enumerate(vals, 1):
            ws.cell(r, c).value = v
    return start


